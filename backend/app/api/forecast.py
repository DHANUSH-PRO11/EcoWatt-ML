from typing import List
from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session
from backend.app.database import get_db
from backend.app.schemas.forecast import ForecastRequest, ForecastResponse, ForecastItem
from backend.app.services.forecast_service import generate_forecast, get_forecast_history

router = APIRouter(prefix="/api/forecast", tags=["Forecasting"])


@router.post("", response_model=ForecastResponse)
def create_forecast(
    request: ForecastRequest,
    db: Session = Depends(get_db),
):
    """
    Generate recursive multi-step energy forecast for future horizons:
    - 1 hour (next-hour)
    - 24 hours (next-day)
    - 168 hours (next 7 days)
    Includes calibrated prediction intervals reflecting error propagation.
    """
    try:
        return generate_forecast(db, request)
    except ValueError as ve:
        raise HTTPException(status_code=400, detail=str(ve))
    except RuntimeError as re:
        raise HTTPException(status_code=503, detail=str(re))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Forecasting engine error: {str(e)}")


@router.get("/history", response_model=List[ForecastItem])
def read_forecast_history(
    limit: int = Query(72, ge=1, le=500),
    db: Session = Depends(get_db),
):
    """Retrieve historical forecast predictions previously generated by the ML engine."""
    return get_forecast_history(db, limit=limit)
